export const getDepressionLevel = (score: number): string => {
  if (score >= 0 && score <= 5) return 'Норма'
  if (score >= 6 && score <= 10) return 'Нормальное, но несчастливое состояние'
  if (score >= 11 && score <= 25) return 'Легкая депрессия'
  if (score >= 26 && score <= 50) return 'Умеренная депрессия'
  if (score >= 51 && score <= 75) return 'Тяжелая депрессия'
  if (score >= 76 && score <= 100) return 'Экстремальная депрессия'
  return 'Неизвестно'
}

export const getDepressionColor = (score: number): string => {
  if (score >= 0 && score <= 5) return '#4CAF50'
  if (score >= 6 && score <= 10) return '#8BC34A'
  if (score >= 11 && score <= 25) return '#FFC107'
  if (score >= 26 && score <= 50) return '#FF9800'
  if (score >= 51 && score <= 75) return '#FF5722'
  if (score >= 76 && score <= 100) return '#F44336'
  return '#9E9E9E'
}

